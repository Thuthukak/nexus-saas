<?php

declare(strict_types=1);

namespace App\Kernel\Dtos;

use App\Kernel\Dto;

/**
 * One inbound email, normalised by an intake adapter (IMAP poller today, a provider webhook later).
 * It carries the ORIGINAL recipient address because the signed token lives in its local part.
 * Deliberately has no In-Reply-To / References: those headers are forgeable and are never used for routing.
 */
final readonly class InboundEmailDTO extends Dto
{
    public function __construct(
        public string $messageId,        // without angle brackets
        public string $recipient,        // the original recipient on the reply domain, e.g. reply+...@reply.example.com
        public string $fromAddress,
        public string $subject,
        public string $textBody,         // full plain text (html converted when there was no text part)
        public string $replyText,        // textBody without quoted history and signature, never empty if textBody is not
        public string $receivedAt,       // ISO 8601
        public string $source,           // 'imap' | 'webhook' | ...
        public ?string $fromName = null,
        public ?string $htmlBody = null,
        public bool $autoGenerated = false, // auto-reply, bounce or bulk mail (set by the adapter from headers)
    ) {
    }
}
