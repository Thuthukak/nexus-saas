<?php

declare(strict_types=1);

namespace Modules\Core\Inbound;

use App\Kernel\Dtos\InboundEmailDTO;
use App\Kernel\Dtos\InboundEmailReceived;
use App\Kernel\Dtos\InboundEmailReceivedDTO;
use App\Platform\Modules\ModuleManager;
use App\Tenancy\Tenant;
use App\Tenancy\TenantRunner;
use Illuminate\Support\Facades\DB;
use Modules\Core\Email\ReplyTokenSigner;

/**
 * CoreInboundEmailRouting. The ONE place inbound mail is routed. It knows nothing about how a message arrived:
 * every intake adapter builds an InboundEmailDTO and calls route().
 *
 *  1. the recipient must be on the reply domain
 *  2. the signed token in its local part must verify (HMAC, hash_equals) BEFORE any tenant lookup or matching.
 *     The forgeable In-Reply-To / References headers are never consulted (the DTO does not even carry them)
 *  3. auto-replies, bounces, oversize and our own mail are refused
 *  4. tenant and record type come from the verified signature; the tenant must exist, be active, and have the
 *     record type's owning module enabled
 *  5. at most once per Message-ID: claimed in the same transaction that dispatches the event, so a failing
 *     listener rolls the claim back and the message can be retried
 *  6. InboundEmailReceived is dispatched with the tenant context set
 */
final class InboundEmailRouter
{
    public const MAX_TEXT_BYTES = 200_000;
    public const MAX_HTML_BYTES = 500_000;

    public function __construct(
        private readonly ReplyTokenSigner $signer,
        private readonly InboundRecordTypeRegistry $types,
        private readonly ModuleManager $modules,
        private readonly TenantRunner $runner,
    ) {
    }

    public function route(InboundEmailDTO $email): RouteOutcome
    {
        $messageId = trim($email->messageId, " <>\t\r\n");
        if ($messageId === '' || strlen($messageId) > 998) {
            return RouteOutcome::rejected('invalid_message_id');   // nothing to dedupe on, nothing logged
        }

        $at = strrpos($email->recipient, '@');
        $local = $at === false ? '' : substr($email->recipient, 0, $at);
        $domain = $at === false ? '' : strtolower(substr($email->recipient, $at + 1));
        $key = hash('sha256', strtolower($messageId).'|'.strtolower($email->recipient));

        if ($domain !== strtolower((string) config('tenancy.reply_domain'))) {
            return $this->reject($key, 'wrong_domain', $email);
        }

        $ref = $this->signer->verify($local);
        if ($ref === null) {
            return $this->reject($key, 'bad_signature', $email);
        }

        if ($email->autoGenerated) {
            return $this->reject($key, 'auto_generated', $email, $ref['tenant_id']);
        }
        if (strlen($email->textBody) > self::MAX_TEXT_BYTES || strlen((string) $email->htmlBody) > self::MAX_HTML_BYTES) {
            return $this->reject($key, 'too_large', $email, $ref['tenant_id']);
        }
        $from = strtolower($email->fromAddress);
        if ($from === strtolower((string) config('mail.from.address')) || str_ends_with($from, '@'.strtolower((string) config('tenancy.reply_domain')))) {
            return $this->reject($key, 'own_address', $email, $ref['tenant_id']);   // mail loop
        }

        $owner = $this->types->moduleFor($ref['record_type']);
        if ($owner === null) {
            return $this->reject($key, 'unknown_record_type', $email, $ref['tenant_id']);
        }

        $tenant = Tenant::query()->find($ref['tenant_id']);
        if ($tenant === null) {
            return $this->reject($key, 'unknown_tenant', $email);
        }
        if ($tenant->status !== Tenant::ACTIVE) {
            return $this->reject($key, 'tenant_inactive', $email, $tenant->id);
        }
        if (! in_array($owner, $this->modules->activeModules($tenant->id), true)) {
            return $this->reject($key, 'module_disabled', $email, $tenant->id);
        }

        return $this->runner->run($tenant->id, function () use ($key, $ref, $email, $tenant): RouteOutcome {
            $claimed = DB::table('inbound_email_log')->insertOrIgnore([
                'dedupe_key' => $key, 'tenant_id' => $tenant->id, 'record_type' => $ref['record_type'], 'record_id' => $ref['record_id'],
                'status' => RouteOutcome::DELIVERED, 'reason' => null, 'source' => $email->source, 'created_at' => now(),
            ]);
            if ($claimed === 0) {
                return RouteOutcome::duplicate();
            }

            event(new InboundEmailReceived(new InboundEmailReceivedDTO($tenant->id, $ref['record_type'], $ref['record_id'], $email)));

            return RouteOutcome::delivered();
        });
    }

    /** Records the refusal (once per message) so re-polling is harmless and failures can be inspected. Stores no addresses or content. */
    private function reject(string $key, string $reason, InboundEmailDTO $email, ?string $tenantId = null): RouteOutcome
    {
        DB::table('inbound_email_log')->insertOrIgnore([
            'dedupe_key' => $key,
            'tenant_id' => $tenantId !== null && Tenant::query()->whereKey($tenantId)->exists() ? $tenantId : null,
            'record_type' => null, 'record_id' => null,
            'status' => RouteOutcome::REJECTED, 'reason' => $reason, 'source' => $email->source, 'created_at' => now(),
        ]);

        return RouteOutcome::rejected($reason);
    }
}
