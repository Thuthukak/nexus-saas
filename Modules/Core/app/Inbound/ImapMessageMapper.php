<?php

declare(strict_types=1);

namespace Modules\Core\Inbound;

use App\Kernel\Dtos\InboundEmailDTO;

/**
 * Intake adapter logic for mailbox messages: build an InboundEmailDTO. It does NOT verify anything and does NOT
 * route; that is the router's job. Pure, so it is tested without a mailbox.
 */
final class ImapMessageMapper
{
    public function __construct(private readonly string $replyDomain, private readonly string $source = 'imap')
    {
    }

    /** @return InboundEmailDTO|null null when the message cannot be turned into a DTO at all (no id, no sender, nothing for our domain) */
    public function map(RawImapMessage $raw): ?InboundEmailDTO
    {
        $h = RawHeaderParser::parse($raw->headers);

        $messageId = trim($h['message-id'][0] ?? '', " <>\t");
        $from = RawHeaderParser::addresses($h['from'][0] ?? '')[0] ?? null;
        $recipient = $this->recipient($h);
        if ($messageId === '' || $from === null || $recipient === null) {
            return null;
        }

        $text = $raw->text !== null && trim($raw->text) !== '' ? $raw->text : self::htmlToText((string) $raw->html);
        $text = str_replace(["\r\n", "\r"], "\n", $text);

        $time = isset($h['date'][0]) ? strtotime($h['date'][0]) : false;

        return new InboundEmailDTO(
            messageId: $messageId,
            recipient: $recipient,
            fromAddress: $from,
            subject: mb_substr(preg_replace('/[\r\n]+/', ' ', $h['subject'][0] ?? '') ?? '', 0, 200),
            textBody: $text,
            replyText: ReplyTextTrimmer::trim($text),
            receivedAt: gmdate('c', $time !== false ? $time : time()),
            source: $this->source,
            fromName: RawHeaderParser::displayName($h['from'][0] ?? ''),
            htmlBody: $raw->html !== null && trim($raw->html) !== '' ? $raw->html : null,
            autoGenerated: self::isAutoGenerated($h, $from),
        );
    }

    /**
     * The ORIGINAL recipient, read from Delivered-To / X-Original-To first (a catch-all can lose it from To when the mail
     * was BCC'd or forwarded), then To and Cc. Only addresses on the reply domain with a reply+ local part count.
     *
     * @param array<string, list<string>> $h
     */
    private function recipient(array $h): ?string
    {
        foreach (['delivered-to', 'x-original-to', 'to', 'cc'] as $name) {
            foreach ($h[$name] ?? [] as $value) {
                foreach (RawHeaderParser::addresses($value) as $addr) {
                    if (str_starts_with($addr, 'reply+') && str_ends_with($addr, '@'.strtolower($this->replyDomain))) {
                        return $addr;
                    }
                }
            }
        }

        return null;
    }

    /** @param array<string, list<string>> $h */
    public static function isAutoGenerated(array $h, string $from): bool
    {
        $auto = strtolower(trim($h['auto-submitted'][0] ?? ''));
        $precedence = strtolower(trim($h['precedence'][0] ?? ''));

        return ($auto !== '' && $auto !== 'no')
            || in_array($precedence, ['bulk', 'junk', 'list', 'auto_reply'], true)
            || isset($h['x-autoreply']) || isset($h['x-autorespond'])
            || (isset($h['return-path']) && preg_match('/^<?\s*>?$/', $h['return-path'][0]) === 1)   // empty envelope sender: a bounce
            || preg_match('/^(mailer-daemon|postmaster)@/i', $from) === 1;
    }

    public static function htmlToText(string $html): string
    {
        $html = preg_replace('#<(script|style)\b[^>]*>.*?</\1>#is', '', $html) ?? '';
        $html = preg_replace('#<(br|/p|/div|/li|/tr|/h[1-6])\b[^>]*>#i', "\n", $html) ?? '';
        $text = html_entity_decode(strip_tags($html), ENT_QUOTES | ENT_HTML5, 'UTF-8');

        return trim(preg_replace("/\n{3,}/", "\n\n", $text) ?? '');
    }
}
