<?php

use Modules\Core\Email\ReplyTokenSigner;
use Modules\Core\Inbound\ImapMessageMapper;
use Modules\Core\Inbound\InboundRecordTypeRegistry;
use Modules\Core\Inbound\RawHeaderParser;
use Modules\Core\Inbound\RawImapMessage;
use Modules\Core\Inbound\ReplyTextTrimmer;

const IN_TENANT = '0b9f6c34-5a1e-4d52-9a57-3f6a1c2d8e90';
const IN_DOMAIN = 'reply.example.com';

function inAddr(string $key = 'k'): string
{
    return (new ReplyTokenSigner($key))->issue(IN_TENANT, 'ticket', '42').'@'.IN_DOMAIN;
}

function inHeaders(array $o = []): string
{
    $h = array_merge([
        'Delivered-To' => inAddr(), 'From' => '"Tess Customer" <tess@customer.test>', 'To' => 'support@acme.test',
        'Subject' => 'Re: Printer', 'Message-ID' => '<abc123@customer.test>', 'Date' => 'Mon, 19 Oct 2026 10:00:00 +0000',
    ], $o);
    $out = '';
    foreach ($h as $k => $v) {
        if ($v !== null) {
            $out .= "{$k}: {$v}\r\n";
        }
    }

    return $out;
}

function inRaw(array $headers = [], ?string $text = "Thanks, that fixed it.\n\nOn Mon, 19 Oct 2026, Ada wrote:\n> Did you restart it?", ?string $html = null, int $size = 500): RawImapMessage
{
    return new RawImapMessage('7', inHeaders($headers), $text, $html, $size);
}

// ---- header parser ----

it('parses, unfolds and lower-cases headers, keeping repeated headers in order', function () {
    $h = RawHeaderParser::parse("Subject: Hello\r\n  folded line\r\nX-Thing: 1\r\nx-thing: 2\r\nBad Header Name: x\r\nnot a header\r\n\r\nBody: ignored");

    expect($h['subject'])->toBe(['Hello folded line'])->and($h['x-thing'])->toBe(['1', '2'])
        ->and($h)->not->toHaveKey('body')->and($h)->not->toHaveKey('bad header name');
});

it('decodes encoded-word headers', function () {
    expect(RawHeaderParser::parse("Subject: =?UTF-8?B?w4BkYQ==?=\r\n")['subject'][0])->toBe('Àda');
});

it('extracts addresses and display names', function () {
    expect(RawHeaderParser::addresses('"Doe, Jo" <Jo@Example.com>, other@x.test'))->toBe(['jo@example.com', 'other@x.test'])
        ->and(RawHeaderParser::addresses('reply+abc.ticket-42_xyz@reply.example.com'))->toBe(['reply+abc.ticket-42_xyz@reply.example.com'])
        ->and(RawHeaderParser::addresses('no address here'))->toBe([])
        ->and(RawHeaderParser::displayName('"Tess Customer" <t@c.test>'))->toBe('Tess Customer')
        ->and(RawHeaderParser::displayName('t@c.test'))->toBeNull();
});

// ---- reply trimming ----

it('keeps only what the person just wrote', function (string $input, string $expected) {
    expect(ReplyTextTrimmer::trim($input))->toBe($expected);
})->with([
    'gmail style' => ["Fixed, thanks.\n\nOn Mon, 19 Oct 2026 at 10:00, Ada <ada@acme.test> wrote:\n> Did you restart it?", 'Fixed, thanks.'],
    'wrapped on two lines' => ["Yes.\n\nOn Mon, 19 Oct 2026 at 10:00, Ada Longname\n<ada@acme.test> wrote:\n> q", 'Yes.'],
    'outlook original message' => ["Done.\n\n-----Original Message-----\nFrom: Ada\nSent: Monday", 'Done.'],
    'outlook header block' => ["Done.\n\nFrom: Ada <a@b.test>\nSent: Monday\nTo: me\nSubject: x\n\nold", 'Done.'],
    'signature delimiter' => ["Thanks\n-- \nTess\n0123", 'Thanks'],
    'trailing quote block' => ["Answer\n> quoted\n> more", 'Answer'],
    'no quoting at all' => ["Just one message\nwith two lines", "Just one message\nwith two lines"],
    'crlf' => ["Hi\r\n\r\nOn Mon, 19 Oct 2026, Ada wrote:\r\n> x", 'Hi'],
]);

it('never loses a message that is ALL quoted text', function () {
    $text = "On Mon, 19 Oct 2026, Ada wrote:\n> everything is quoted";

    expect(ReplyTextTrimmer::trim($text))->toBe($text);
});

// ---- mapper ----

it('maps a mailbox message to the normalised DTO', function () {
    $m = (new ImapMessageMapper(IN_DOMAIN))->map(inRaw());

    expect($m->messageId)->toBe('abc123@customer.test')->and($m->recipient)->toBe(inAddr())->and($m->fromAddress)->toBe('tess@customer.test')
        ->and($m->fromName)->toBe('Tess Customer')->and($m->subject)->toBe('Re: Printer')->and($m->source)->toBe('imap')
        ->and($m->replyText)->toBe('Thanks, that fixed it.')->and($m->textBody)->toContain('Did you restart it?')
        ->and($m->receivedAt)->toBe('2026-10-19T10:00:00+00:00')->and($m->autoGenerated)->toBeFalse();
});

it('reads the ORIGINAL recipient from Delivered-To / X-Original-To before To, ignoring other addresses', function () {
    $other = inAddr('someone-else');   // an address on our domain, but not the one a catch-all delivered to
    $m = (new ImapMessageMapper(IN_DOMAIN))->map(inRaw(['Delivered-To' => null, 'X-Original-To' => inAddr(), 'To' => "support@acme.test, {$other}"]));

    expect($m->recipient)->toBe(inAddr());
    $viaTo = (new ImapMessageMapper(IN_DOMAIN))->map(inRaw(['Delivered-To' => null, 'To' => 'support@acme.test, '.inAddr()]));
    expect($viaTo->recipient)->toBe(inAddr());
});

it('returns null when nothing is addressed to the reply domain, or the message has no id or sender', function (array $override) {
    expect((new ImapMessageMapper(IN_DOMAIN))->map(inRaw($override)))->toBeNull();
})->with([
    'wrong domain' => [['Delivered-To' => 'reply+x@other.test', 'To' => 'a@b.test']],
    'no reply+ local part' => [['Delivered-To' => 'help@'.IN_DOMAIN, 'To' => 'a@b.test']],
    'no message id' => [['Message-ID' => null]],
    'no sender' => [['From' => null]],
    'no recipient at all' => [['Delivered-To' => null, 'To' => null]],
]);

it('falls back to the HTML part when there is no text part', function () {
    $m = (new ImapMessageMapper(IN_DOMAIN))->map(inRaw([], null, '<style>p{}</style><p>Hello&nbsp;there</p><p>Second &amp; last</p>'));

    expect($m->textBody)->toContain('Second & last')->not->toContain('<p>')->not->toContain('p{}');
});

it('flags auto-generated mail from its headers', function (array $override, bool $auto) {
    expect((new ImapMessageMapper(IN_DOMAIN))->map(inRaw($override))->autoGenerated)->toBe($auto);
})->with([
    'normal' => [[], false],
    'auto-submitted auto-replied' => [['Auto-Submitted' => 'auto-replied'], true],
    'auto-submitted no' => [['Auto-Submitted' => 'no'], false],
    'precedence bulk' => [['Precedence' => 'bulk'], true],
    'x-autoreply' => [['X-Autoreply' => 'yes'], true],
    'empty return-path (bounce)' => [['Return-Path' => '<>'], true],
    'normal return-path' => [['Return-Path' => '<tess@customer.test>'], false],
    'mailer-daemon sender' => [['From' => 'MAILER-DAEMON@mx.test'], true],
]);

it('does not trust or even read In-Reply-To / References when mapping', function () {
    $m = (new ImapMessageMapper(IN_DOMAIN))->map(inRaw(['In-Reply-To' => '<ticket-1@victim.test>', 'References' => '<ticket-1@victim.test>']));

    expect(array_keys(get_object_vars($m)))->not->toContain('inReplyTo')->not->toContain('references');
});

// ---- record type registry ----

it('lets a module claim a record type and refuses clashes and bad input', function () {
    $r = new InboundRecordTypeRegistry();
    $r->register('Support', 'ticket');
    $r->register('Support', 'ticket');   // idempotent for the owner

    expect($r->moduleFor('ticket'))->toBe('Support')->and($r->moduleFor('invoice'))->toBeNull()
        ->and(fn () => $r->register('Financial', 'ticket'))->toThrow(InvalidArgumentException::class)
        ->and(fn () => $r->register('Nope', 'thing'))->toThrow(InvalidArgumentException::class)
        ->and(fn () => $r->register('Support', 'Ticket'))->toThrow(InvalidArgumentException::class)
        ->and(fn () => $r->register('Support', 'tickets1'))->toThrow(InvalidArgumentException::class);
});
